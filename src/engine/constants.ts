export const CAMERA = {
  /* ---- 透视 ---- */
  /**
   * 透视距离（rem）。不用 Celestial-Web 的 160：160 太远，投影接近正交，
   * z 相关视差几乎看不见。120 在「透视明显」与「不产生鱼眼畸变」之间取平衡。
   */
  PERSPECTIVE: 120,

  /* ---- 空间模型 ---- */
  /**
   * 相邻两区的垂直间距（rem）。
   * **必须是正值**：CSS 里 +Y 是向下，所以正值让索引更大的区块落在更低处，
   * 「向下滚动 = 去下一页」才和普通网页一致。负值会把后面的区块摆到上方。
   */
  VERTICAL_SPACING: 72,
  /** 左右交替的横向振幅（rem） */
  LATERAL_AMPLITUDE: 26,
  /** 基准相机距离（rem） */
  BASE_DISTANCE: 34,
  /** 相机距离的抖动幅度（rem），让每区的镜头感不同 */
  DISTANCE_JITTER: 8,

  /* ---- 连续力学（见 physics.ts） ----
   *
   * 整站只有一个方程：a = F_势能 + F_阻尼 + F_锚定 + F_输入。
   * 果冻与切换是它的不同能量状态，不是不同代码路径。
   *
   * 参数是按数值模拟定的（见 docs/DESIGN.md「连续力学」一节）：
   *  - k=45, c=12 → ζ≈0.89（几乎无过冲）、ω≈6.7 rad/s
   *  - 一次切换约 1.04 秒（实测轨迹见 docs/DESIGN.md），过冲约 2%
   */
  /** 势能强度。近井底角频率 ω = √k */
  PHYSICS_K: 45,
  /** 阻尼系数。阻尼比 ζ = c / (2√k) */
  PHYSICS_DAMPING: 12,
  /** 速度上限（索引/秒），防止极端输入把相机甩出去 */
  PHYSICS_MAX_SPEED: 6,
  /**
   * 滚动输入 → 持续力的增益（索引/秒² per px）。
   * 力在 `INPUT_FORCE_DECAY_MS`（90ms）内衰减，模拟「一次滚轮冲量」。
   */
  PULL_FORCE_GAIN: 0.02,
  /** 滚动输入 → 瞬时速度冲量（索引/秒 per px）。让轻滚也有可感知的推 */
  PULL_IMPULSE_GAIN: 0.0008,
  /**
   * 参与冲量计算的位移上限（px）。
   * 未提交的滚动可能累计很大（阈值 750px），但「微弱滚动」的观感不该
   * 随它线性放大 —— 超过这个值就饱和，果冻幅度封顶。
   */
  PULL_MAX_DELTA: 240,

  /* ---- 输入 ---- */
  /** 一行 wheel 折算的像素 */
  WHEEL_LINE_PX: 16,
  /**
   * 累计位移超过这个值 → 提交 step。
   * 滚轮一格约 100px，所以 750 意味着要连续滚 7–8 格才切换；
   * 在此之前只是「抖动」（pull），不会翻页。
   */
  STEP_THRESHOLD_PX: 750,
  /**
   * 快速手势的判定：速度 ≥ 此值（px/ms）且累计 ≥ STEP_SPEED_MIN_PX → 立即提交。
   *
   * **只对「触控板式」的输入生效** —— 见 TRACKPAD_MAX_EVENT_PX。
   * 这一条的意义是让触控板用力一划不必凑满 750px 也能翻页。
   */
  STEP_SPEED_PX_MS: 4,
  STEP_SPEED_MIN_PX: 240,
  /**
   * 单次事件超过这个像素数就不算「触控板式」，速度分支对它不生效。
   *
   * 为什么需要这一条：滚轮一格是**一个大事件**（约 100px），若按
   * 「delta / 事件间隔」算速度，它是 6.25px/ms —— 比触控板的小步移动还快，
   * 于是两格滚轮就会被速度分支当成猛滑而提交，把 750px 的阈值架空。
   *
   * 真正的区别不在速度，在**粒度**：触控板产生许多小事件，滚轮产生少数大事件。
   * 所以速度分支只在「当前这一格是小步」时才启用。
   */
  TRACKPAD_MAX_EVENT_PX: 40,
  /** 手势间隔超过此值（ms）视为新手势 */
  GESTURE_GAP_MS: 160,
  /** 提交后的冷却（ms）：吞掉触控板惯性的尾巴 */
  GESTURE_COOLDOWN_MS: 260,
  /** 转场期间是否允许排队（0 = 忽略，与访谈一致） */
  QUEUE_DEPTH: 0,

  /* ---- 动态倾斜 ---- */
  /** 速度 → 倾斜角的增益（deg per rem/ms） */
  TILT_VEL_GAIN: 26,
  /** 动态倾斜封顶（deg） */
  TILT_MAX_DEG: 3.2,

  /* ---- 运动模糊 ---- */
  /** 速度 → blur 半径（px per rem/ms） */
  BLUR_SPEED_GAIN: 22,
  BLUR_MAX_PX: 6,
  /** 速度 → 沿运动轴的拉伸比例 */
  STRETCH_SPEED_GAIN: 0.22,
  STRETCH_MAX: 0.06,
  /** 拖影层最大不透明度 */
  STREAK_MAX_OPACITY: 0.18,

  /* ---- 帧循环 ---- */
  /** dt 上限（ms）：标签页切回来时不至于一帧跳完 */
  MAX_DT_MS: 100,
}
